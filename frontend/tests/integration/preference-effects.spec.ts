import { expect, test } from '@playwright/test'

test('real preview, saved alerts and dashboard use the same period and persisted observations', async ({ page, request }, testInfo) => {
  test.setTimeout(90000)
  const to = new Date(); to.setUTCSeconds(0,0)
  const from = new Date(to.getTime()-86400000)
  const period={kind:'custom',from:from.toISOString(),to:to.toISOString()}
  const before=await (await request.get(`http://127.0.0.1:4301/analysis/summary?${new URLSearchParams({from:period.from,to:period.to,granularity:'hour'})}`)).json()
  await page.goto('/login')
  await page.getByLabel('E-mail institucional').fill('preferences@example.test')
  await page.getByLabel('Senha',{exact:true}).fill('Fixture-preferences-2026')
  await page.getByRole('button',{name:'Entrar',exact:true}).click()
  await expect(page).toHaveURL(url=>url.pathname==='/')
  await page.getByRole('link',{name:'Metodologia',exact:true}).click()
  await page.getByLabel('Limite em edição',{exact:true}).fill('0')
  await page.getByLabel('Período de aplicação',{exact:true}).selectOption('custom')
  await page.getByLabel('Início (UTC)',{exact:true}).fill(period.from.slice(0,16))
  const previewResponse=page.waitForResponse(response=>new URL(response.url()).pathname==='/me/preferences/alerts/preview' && response.request().postDataJSON().energy.period?.kind==='custom' && response.request().postDataJSON().energy.period?.to===period.to).then(response=>response.json())
  await page.getByLabel('Fim exclusivo (UTC)',{exact:true}).fill(period.to.slice(0,16))
  const preview=await previewResponse
  const expected=preview.applications.find((item:{applicationId:string})=>item.applicationId==='quality-api').evaluations.find((item:{metric:string})=>item.metric==='energy')
  expect(expected.status).toBe('exceeded')
  expect(expected.value).toBeGreaterThan(0)
  expect(expected.from).toBe(period.from)
  expect(expected.to).toBe(period.to)
  await expect(page.getByRole('region',{name:'Meus avisos ambientais',exact:true}).getByText('Limite ultrapassado',{exact:false}).first()).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('preference-preview.png'), fullPage: true })
  const savedResponse=page.waitForResponse(response=>new URL(response.url()).pathname==='/me/preferences/energy' && response.request().method()==='PUT').then(response=>response.json())
  await page.getByRole('button',{name:'Salvar minhas preferências',exact:true}).click()
  expect((await savedResponse).value.period).toEqual(period)
  await expect(page.getByText('Preferências salvas',{exact:true})).toBeVisible()
  await page.getByRole('tab',{name:'Padrão das análises',exact:true}).click()
  await page.getByLabel('Período de aplicação',{exact:true}).selectOption('custom')
  await page.getByLabel('Início (UTC)',{exact:true}).fill(period.from.slice(0,16))
  await page.getByLabel('Fim exclusivo (UTC)',{exact:true}).fill(period.to.slice(0,16))
  await page.getByRole('button',{name:'Salvar minhas preferências',exact:true}).click()
  await expect(page.getByText('Preferências salvas',{exact:true})).toBeVisible()
  const alertsResponse=page.waitForResponse(response=>new URL(response.url()).pathname==='/me/preferences/alerts').then(response=>response.json())
  await page.getByRole('link',{name:'Dashboard',exact:true}).click()
  const alerts=await alertsResponse
  const saved=alerts.applications.find((item:{applicationId:string})=>item.applicationId==='quality-api').evaluations.find((item:{metric:string})=>item.metric==='energy')
  expect(saved).toEqual(expected)
  await expect(page).toHaveURL(url=>url.searchParams.get('period')==='custom' && url.searchParams.get('from')===period.from && url.searchParams.get('to')===period.to)
  const actual=await (await request.get(`http://127.0.0.1:4301/analysis/summary?${new URLSearchParams({from:period.from,to:period.to,granularity:'hour'})}`)).json()
  expect(actual.totals).toEqual(before.totals)
  expect(actual.applications).toEqual(before.applications)
  await page.getByRole('button',{name:'7 dias',exact:true}).click()
  await expect(page).toHaveURL(url=>url.searchParams.get('period')==='7d' && !url.searchParams.has('from'))
})
